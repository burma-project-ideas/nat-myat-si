    public static NatMyatSiCatalog CreateCatalog()
    {
        var expectedReadingCount = QuestionTexts.Length * Symbols.Length;
        if (ReadingTexts.Length != expectedReadingCount)
        {
            throw new InvalidDataException(
                $"The compiled NatMyatSi catalog must contain {expectedReadingCount} readings.");
        }

        var questions = QuestionTexts
            .Select((text, index) => new NatMyatSiQuestion { Id = index + 1, Text = text })
            .ToArray();
        var readings = new NatMyatSiReading[ReadingTexts.Length];
        var readingIndex = 0;

        foreach (var question in questions)
        {
            foreach (var symbol in Symbols)
            {
                readings[readingIndex] = new NatMyatSiReading
                {
                    QuestionId = question.Id,
                    SymbolId = symbol.Id,
                    Text = ReadingTexts[readingIndex]
                };
                readingIndex++;
            }
        }

        return new NatMyatSiCatalog(questions, Symbols, readings);
    }
